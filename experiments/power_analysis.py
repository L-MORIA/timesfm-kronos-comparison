"""Расчёт мощности для кросс-секционного теста на 14 тикерах MOEX.

Зачем. Шаг 0 показал: текущий бэктест разрешает |IC| >= 0.12…0.22, тогда как
торгуемые дневные факторы живут в зоне 0.02–0.05. Прежде чем менять дизайн,
считаем, сколько наблюдений нужно, чтобы увидеть эффект такого размера.

Единица анализа — НЕ (тикер, дата), а дата: кросс-секционный IC считается
внутри даты по 14 бумагам. Все они — ликвидные крупныеcaps MOEX и движутся
вместе, поэтому число независимых ставок определяется датами, а не
бумагами. Это ровно clustering из power-анализа, и обрабатывается он здесь
явно, а не молча.

Метод: тест на корреляцию (ранговый IC), Fisher z.
    atanh(ρ) · √(n − 3) = z_{1−α/2} + z_power
    => n = ((z_{1−α/2} + z_power) / atanh(ρ))² + 3

Никаких внешних зависимостей: scipy в venv нет, квантили нормального
берём из stdlib statistics.NormalDist.

Поправки, которые обычно забывают и которые применены здесь:
  * множественные сравнения — 5 предикторов × 3 горизонта = 15 тестов,
    поэтому считаем и при Bonferroni α/15;
  * clustering — 14 бумаг в дате дают design effect, НО для кросс-секционного
    IC единица уже дата, поэтому бумаги не тиражируются (псевдорепликации нет);
  * перекрытие окон — устраняется конструктивно: шаг дат = горизонт,
    тогда окна не пересекаются и N_eff = N без поправки Newey-West.
"""
from __future__ import annotations

import math
from statistics import NormalDist

ND = NormalDist()

# Вселенная из kronos-signal/config.yaml — существовала до всех экспериментов.
# YDEX исключён 2026-10-16: минутная и дневная история у него начинается
# только с 2024-07-24 (2.2 года против 12–15 лет у остальных), и одна эта
# бумага схлопывала общий кусок всей вселенной с 12 лет до 2.2.
TICKERS = ["SBER", "GAZP", "LKOH", "SBERP", "VTBR", "FEES", "MOEX", "ROSN",
           "TRNFP", "GMKN", "SNGSP", "MTSS", "AFKS"]
N_TICKERS = len(TICKERS)

# Полная история, замеренная на этапе 1 (ROADMAP.md), баров на тикер.
FULL_HISTORY = {"SBERP": 4954, "GAZP": 3236, "LKOH": 5926}
# Общий сопоставимый кусок с 2021-01-01 — по 1582 баров на тикер.
COMMON_BARS = 1582

# Интрадей: измерено experiments/intraday_recon.py по минутным барам.
INTRADAY_BARS_PER_DAY = 1005   # минутных баров в сутках, включая вечернюю сессию
INTRADAY_COMMON_START = "2014-06-09"   # самый поздний старт среди 13 тикеров
INTRADAY_DAYS = 3125          # 12.4 года × 252 дня

ALPHA = 0.05
POWER = 0.80
N_TESTS = 15          # 5 предикторов × 3 горизонта


def required_n(rho, alpha=ALPHA, power=POWER):
    """Сколько независимых наблюдений нужно, чтобы увидеть корреляцию rho."""
    if not 0 < abs(rho) < 1:
        return float("inf")
    z = ND.inv_cdf(1 - alpha / 2) + ND.inv_cdf(power)
    return (z / math.atanh(rho)) ** 2 + 3


def available_n(bars, horizon, stride=None):
    """Сколько независимых наблюдений даёт история такой длины.

    При stride = horizon окна не перекрываются, поэтому N_eff = N и никакая
    поправка на перекрытие не нужна.
    """
    stride = stride or horizon
    return max(bars // stride, 1)


def mde_for(n, alpha=ALPHA, power=POWER):
    """Минимальный обнаружимый |rho| при данном n.

    ВАЖНО:.power здесь обязателен. Раньше порог считался только по
    z_{1-α/2}, то есть соответствовал мощности 50 %, тогда как required_n
    считался при 80 % (z_{1-α/2}+z_{0.80}). Одна и та же величина была
    описана двумя стандартами, и в отчёте это читалось как противоречие
    (audit 2026-10-25, MB2). Теперь обе функции используют одну конвенцию.
    """
    if n <= 3:
        return float("nan")
    z = ND.inv_cdf(1 - alpha / 2) + ND.inv_cdf(power)
    return math.tanh(z / math.sqrt(n - 3))


def ic_for_ir(ir, n_names):
    """IC, необходимый для заданного информационного отношения.

    Для кросс-секционного портфеля IR ≈ IC · √N. Отсюда — чем больше бумаг,
    тем ниже IC, который нужен для той же доходности на единицу риска.
    """
    return ir / math.sqrt(n_names)


def main():
    print("=" * 78)
    print("МОЩНОСТЬ ТЕСТА: сколько наблюдений нужно для IC нужного размера")
    print("=" * 78)
    print(f"вселенная       : {N_TICKERS} тикеров ({TICKERS[0]}…{TICKERS[-1]})")
    print(f"alpha           : {ALPHA:.2f} двусторонний, power = {POWER:.2f}")
    print(f"тестов в семействе: {N_TESTS} (5 предикторов × 3 горизонта)")
    print()

    # ── 1. Требуемый n по целевому IC ─────────────────────────────
    print("=" * 78)
    print("1. ТРЕБУЕМОЕ ЧИСЛО НЕЗАВИСИМЫХ НАБЛЮДЕНИЙ")
    print("=" * 78)
    a_bonf = ALPHA / N_TESTS
    print(f"{'целевой |IC|':>12}{'n при alpha=.05':>19}{'n при Bonferroni':>20}")
    print("-" * 51)
    rows = []
    for ic in (0.02, 0.03, 0.05, 0.08, 0.10, 0.13, 0.15, 0.20):
        n0 = required_n(ic)
        nb = required_n(ic, alpha=a_bonf)
        rows.append((ic, n0, nb))
        print(f"{ic:>12.2f}{n0:>19.0f}{nb:>20.0f}")
    print()
    print(f"Bonferroni поднимает alpha до {a_bonf:.4f} из-за {N_TESTS} тестов")
    print("в семействе — это требование, а не украшение: без него любой из 15")
    print("результатов проходит с вероятностью 5% чисто случайно.")
    print()

    # ── 2. Что реально доступно ────────────────────────────────────
    print("=" * 78)
    print("2. ЧТО РЕАЛЬНО ДОСТУПНО (шаг дат = горизонт, окна не перекрываются)")
    print("=" * 78)
    print(f"{'история':>26}{'h':>4}{'N набл.':>10}{'MDE':>9}{'IC=0.05':>10}"
          f"{'IC=0.03':>9}")
    print("-" * 68)

    for label, bars in (("с 2021, общий кусок", COMMON_BARS),
                        ("полная (LKOH, 2003)", FULL_HISTORY["LKOH"]),
                        ("полная (SBERP, 2007)", FULL_HISTORY["SBERP"])):
        for h in (1, 3, 5, 10, 20, 30, 90):
            n = available_n(bars, h)
            m = mde_for(n)
            ok5 = "да" if n >= required_n(0.05) else "нет"
            ok3 = "да" if n >= required_n(0.03) else "нет"
            print(f"{label:>26}{h:>4}{n:>10}{m:>9.3f}{ok5:>10}{ok3:>9}")
        print()

    # ── 3. Сколько вообще нужно лет ───────────────────────────────
    print("=" * 78)
    print("3. СКОЛЬКО ЛЕТ ИСТОРИИ НУЖНО ПРИ ШАГЕ = ГОРИЗОНТ")
    print("=" * 78)
    bars_per_year = 252
    print(f"{'целевой |IC|':>12}{'h':>4}{'нужно баров':>13}{'нужно лет':>12}"
          f"{'хватит ли LKOH с 2003':>22}")
    print("-" * 63)
    have = FULL_HISTORY["LKOH"]
    for ic, _, _ in rows:
        for h in (1, 5):
            need = required_n(ic) * h
            yrs = need / bars_per_year
            print(f"{ic:>12.2f}{h:>4}{need:>13.0f}{yrs:>12.1f}"
                  f"{('да, ' + str(int(have - need)) + ' с запасом') if need <= have else 'НЕТ':>22}")
    print()

    # ── 4. Сколько IC нужно ради приемлемого IR ────────────────────
    print("=" * 78)
    print("4. СКОЛЬКО IC НУЖЕН ДЛЯ ПРИЕМЛЕМОГО IR (IR = IC·√N)")
    print("=" * 78)
    print(f"{'число бумаг':>12}{'IR=0.5':>12}{'IR=1.0':>12}{'наш MDE h=5':>15}")
    print("-" * 51)
    mde_h5 = mde_for(available_n(COMMON_BARS, 5))
    for k in (3, 10, 14, 30, 50, 100):
        print(f"{k:>12}{ic_for_ir(0.5, k):>12.3f}{ic_for_ir(1.0, k):>12.3f}"
              f"{mde_h5:>15.3f}")
    print()
    print("Чем больше бумаг, тем ниже IC, достаточный для той же доходности на")
    print("единицу риска. Три бумаги из старого проекта требовали IC 0.29 при")
    print(f"IR=0.5 — это заведомо вне достижимого. {N_TICKERS} бумаг требуют "
          f"{ic_for_ir(0.5, N_TICKERS):.2f}.")
    print()

    # ── 5. Итог ────────────────────────────────────────────────────
    print("=" * 78)
    print("ВЫВОД")
    print("=" * 78)
    best_ic = max(ic for ic, _, _ in rows
                  if required_n(ic, alpha=a_bonf) <= available_n(FULL_HISTORY["LKOH"], 1))
    print(f"Полная история, h=1, Bonferroni: N = {available_n(FULL_HISTORY['LKOH'], 1)},")
    print(f"MDE = {mde_for(available_n(FULL_HISTORY['LKOH'], 1)):.3f}.")
    print(f"Достижимый потолок обнаруживаемости — |IC| = {best_ic:.2f}.")
    print()
    print("Горизонты 30/60/90 закрыты арифметически: при шаге = горизонт")
    print(f"полная история даёт всего {available_n(FULL_HISTORY['LKOH'], 90)} независимых")
    print(f"наблюдений, MDE = {mde_for(available_n(FULL_HISTORY['LKOH'], 90)):.3f}.")
    print("Никакое расширение вселенной это не чинит — потолок задан горизонтом.")

    # ── 6. Интрадей как единственный путь к IC 0.02–0.03 ───────────
    print()
    print("=" * 78)
    print("5. ИНТРАДЕЙ: ЕДИНСТВЕННЫЙ ПУТЬ К ЗОНЕ IC 0.02–0.03")
    print("=" * 78)
    print("Все числа ниже — ИЗМЕРЕННЫЕ, не допущения (experiments/intraday_recon.py):")
    print()
    print("  * ISS не отдаёт 5-минутных свечей вообще. interval=4 — это КВАРТАЛ")
    print("    (контрольная проверка: 15 дней января 2015 вернули одну свечу с")
    print("    begin=2015-01-01, end=2015-03-31). Пятиминутные бары получаются")
    print("    агрегацией из минутных, как это делает kronos-signal.")
    print("  * Минутная история глубокая: 13 тикеров с 2011–2014.")
    print("  * В СЕССИИ 1005 минутных баров, а не ~113. Вечерняя торговля входит")
    print("    в сутки целиком. В 5-минутном эквиваленте это 201 бар.")
    print("  * Сумма объёмов минутных баров сходится с дневной свечой до 1e-3,")
    print("    нулевых баров 0% — день собирается без потерь.")
    print()
    bars_5m_day = 1005 // 5
    print(f"{'h (5м баров)':>13}{'окно':>10}{'N набл.':>10}{'MDE':>9}"
          f"{'IC=0.03':>9}{'IC=0.02':>9}")
    print("-" * 60)
    for h in (6, 12, 24, 48, 96):
        per_day = max(bars_5m_day // h, 1)
        n = per_day * INTRADAY_DAYS
        m = mde_for(n)
        ok3 = "да" if n >= required_n(0.03) else "нет"
        ok2 = "да" if n >= required_n(0.02) else "нет"
        print(f"{h:>13}{f'{h * 5 / 60:.1f} ч':>10}{n:>10,}{m:>9.3f}"
              f"{ok3:>9}{ok2:>9}")
    print()
    print(f"шаг дат = горизонт, {INTRADAY_DAYS:,} дней общей истории, "
          f"{bars_5m_day} баров в сессии.")
    print("Окна не перекрываются ни внутри дня, ни между днями — поправка")
    print("Newey-West не нужна вовсе.")
    print()
    print("Оговорки, которые снимают этот расчёт обратно:")
    print("  * внутридневные бары автокоррелированы сильнее дневных, поэтому")
    print("    N ниже номинального и MDE выше показанного — это главная")
    print("    неизвестная, её снимает только замер на реальных данных;")
    print("  * вечерняя сессия в 1005 баров ликвидностью сильно ниже основной;")
    print("    смешивать их в один ряд — значит смешивать два режима. Возможно,")
    print("    основную сессию надо отрезать явно;")
    print("  * на горизонте 1–2 часа издержки (спред + комиссия) съедают сигнал")
    print("    размера IC 0.02 целиком — считать надо валовую доходность;")
    print("  * метки времени ISS приходят в неочевидном поясе (сессия 06:59…23:49")
    print("    при эталонных 09:50–23:50 MSK) — границы агрегации надо")
    print("    зафиксировать явно, иначе бары по UTC и по MSK разойдутся.")
    print()
    print("Вывод: интрадей-дизайн реален и по мощности, и по данным. Открытым")
    print("остаётся не вопрос «хватит ли», а вопрос «переживёт ли сигнал")
    print("издержки» — и он решается только расчётом валовой доходности.")


